-- GestionCabinet : schéma PostgreSQL (Supabase), multi-cabinets.
--
-- Exécuté par database/install.php avec search_path = schéma privé de l'application
-- (DB_SCHEMA, "cabinet" par défaut) : ce schéma n'est PAS exposé par l'API REST de Supabase.
-- {{APP_ROLE}} est remplacé par le rôle de connexion de l'application (DB_USER).
--
-- Toutes les tables métier portent clinic_id. Les clés étrangères composites
-- (clinic_id, x_id) empêchent, au niveau de la base, de lier un enregistrement
-- à une donnée d'un autre cabinet. Le script est idempotent (relançable).

create table if not exists clinics (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 150),
  slug text not null unique check (slug ~ '^[a-z0-9-]{2,60}$'),
  email text,
  phone text,
  address text,
  currency text not null default 'TND',
  slot_minutes smallint not null default 30 check (slot_minutes between 5 and 240),
  chairs smallint not null default 1 check (chairs between 1 and 20),
  opening_hours jsonb not null,
  portal_enabled boolean not null default true,
  invoice_seq integer not null default 0 check (invoice_seq >= 0),
  created_at timestamptz not null default now()
);

create table if not exists patients (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references clinics (id) on delete cascade,
  first_name text not null check (char_length(first_name) <= 80),
  last_name text not null check (char_length(last_name) <= 80),
  birth_date date,
  gender text check (gender in ('F', 'M', 'O')),
  phone text,
  email text,
  address text,
  insurance_number text,
  medical_history text,
  allergies text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  unique (clinic_id, id)
);
create index if not exists patients_name_idx on patients (clinic_id, last_name, first_name);

create table if not exists users (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references clinics (id) on delete cascade,
  patient_id bigint,
  role text not null check (role in ('admin', 'dentist', 'secretary', 'patient')),
  name text not null,
  email text not null,
  password_hash text not null,
  is_active boolean not null default true,
  must_change_password boolean not null default false,
  mfa_enabled boolean not null default false,
  mfa_secret text,
  mfa_last_step bigint not null default 0,
  mfa_recovery text,
  session_epoch integer not null default 0,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  unique (clinic_id, id),
  unique (clinic_id, email),
  foreign key (clinic_id, patient_id) references patients (clinic_id, id)
);
create index if not exists users_email_idx on users (email);
create index if not exists users_patient_idx on users (clinic_id, patient_id);

create table if not exists treatments (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references clinics (id) on delete cascade,
  name text not null check (char_length(name) <= 120),
  price numeric(12, 3) not null default 0 check (price >= 0),
  duration_minutes smallint not null default 30 check (duration_minutes between 5 and 480),
  is_active boolean not null default true,
  unique (clinic_id, id)
);

create table if not exists appointments (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references clinics (id) on delete cascade,
  patient_id bigint not null,
  dentist_id bigint,
  treatment_id bigint,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'confirmed' check (status in ('pending', 'confirmed', 'completed', 'cancelled', 'no_show')),
  reason text,
  notes text,
  source text not null default 'staff' check (source in ('staff', 'portal')),
  created_by bigint,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at),
  unique (clinic_id, id),
  foreign key (clinic_id, patient_id) references patients (clinic_id, id),
  foreign key (clinic_id, dentist_id) references users (clinic_id, id),
  foreign key (clinic_id, treatment_id) references treatments (clinic_id, id)
);
create index if not exists appointments_time_idx on appointments (clinic_id, starts_at);
create index if not exists appointments_dentist_idx on appointments (clinic_id, dentist_id, starts_at);
create index if not exists appointments_patient_idx on appointments (clinic_id, patient_id, starts_at);
create index if not exists appointments_treatment_idx on appointments (clinic_id, treatment_id);

create table if not exists procedures (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references clinics (id) on delete cascade,
  patient_id bigint not null,
  dentist_id bigint,
  treatment_id bigint,
  performed_on date not null,
  tooth text,
  description text not null,
  created_at timestamptz not null default now(),
  foreign key (clinic_id, patient_id) references patients (clinic_id, id),
  foreign key (clinic_id, dentist_id) references users (clinic_id, id),
  foreign key (clinic_id, treatment_id) references treatments (clinic_id, id)
);
create index if not exists procedures_patient_idx on procedures (clinic_id, patient_id, performed_on);
create index if not exists procedures_dentist_idx on procedures (clinic_id, dentist_id);
create index if not exists procedures_treatment_idx on procedures (clinic_id, treatment_id);

create table if not exists invoices (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references clinics (id) on delete cascade,
  patient_id bigint not null,
  number text not null,
  issued_on date not null,
  total numeric(12, 3) not null default 0 check (total >= 0),
  paid numeric(12, 3) not null default 0 check (paid >= 0),
  status text not null default 'unpaid' check (status in ('unpaid', 'partial', 'paid', 'cancelled')),
  notes text,
  created_by bigint,
  created_at timestamptz not null default now(),
  unique (clinic_id, id),
  unique (clinic_id, number),
  foreign key (clinic_id, patient_id) references patients (clinic_id, id)
);
create index if not exists invoices_status_idx on invoices (clinic_id, status);
create index if not exists invoices_patient_idx on invoices (clinic_id, patient_id);

create table if not exists invoice_items (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null,
  invoice_id bigint not null,
  description text not null,
  quantity smallint not null default 1 check (quantity between 1 and 999),
  unit_price numeric(12, 3) not null,
  line_total numeric(12, 3) not null,
  foreign key (clinic_id, invoice_id) references invoices (clinic_id, id) on delete cascade
);
create index if not exists invoice_items_invoice_idx on invoice_items (clinic_id, invoice_id);

create table if not exists payments (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null,
  invoice_id bigint not null,
  amount numeric(12, 3) not null check (amount > 0),
  method text not null check (method in ('cash', 'card', 'check', 'transfer', 'insurance')),
  paid_on date not null,
  reference text,
  created_by bigint,
  created_at timestamptz not null default now(),
  foreign key (clinic_id, invoice_id) references invoices (clinic_id, id) on delete cascade
);
create index if not exists payments_invoice_idx on payments (clinic_id, invoice_id);
create index if not exists payments_date_idx on payments (clinic_id, paid_on);

create table if not exists rate_limits (
  bucket text primary key,
  hits integer not null default 0,
  window_start bigint not null
);
create index if not exists rate_limits_window_idx on rate_limits (window_start);

create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  clinic_id bigint,
  user_id bigint,
  event text not null,
  severity text not null default 'info' check (severity in ('info', 'warning', 'critical')),
  ip text not null,
  user_agent text,
  details text,
  created_at timestamptz not null default now()
);
create index if not exists audit_log_clinic_idx on audit_log (clinic_id, created_at);
create index if not exists audit_log_event_idx on audit_log (event, created_at);

-- patients.updated_at maintained by the database (MySQL "ON UPDATE CURRENT_TIMESTAMP" equivalent)
create or replace function set_updated_at() returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists patients_set_updated_at on patients;
create trigger patients_set_updated_at
  before update on patients
  for each row execute function set_updated_at();

-- Row Level Security on every table: only the application role gets a policy.
-- Supabase's API roles (anon, authenticated) have no policy, so even if this schema were
-- ever exposed through the REST API, every query from it would return nothing.
do $$
declare
  t text;
begin
  foreach t in array array['clinics', 'patients', 'users', 'treatments', 'appointments', 'procedures',
                           'invoices', 'invoice_items', 'payments', 'rate_limits', 'audit_log']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists app_full_access on %I', t);
    execute format('create policy app_full_access on %I for all to {{APP_ROLE}} using (true) with check (true)', t);
  end loop;
end;
$$;
